// Generates the files the Sigge plugin carries so that it works without a connection:
// the frameworks as Markdown, the AI-pattern checker as a standalone script, and the
// reference files each skill needs a copy of (a skill must be complete on its own,
// because some clients install skills one by one).
//
//   npm run build:plugin        writes the files
//   tsx scripts/build-plugin.mjs --check   fails if a committed file is out of date
import { readFile, writeFile, mkdir, rm, readdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCopyLibrary } from '../copy/library.ts';
import { categoryLabels } from '../copy/locale.ts';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SKILLS = 'plugins/sigge/skills';
const NOTE = '<!-- Generated by scripts/build-plugin.mjs from data/copy-frameworks. Edit the data, not this file. -->';

const words = {
  sv: {
    index: 'Ramverk', intro: 'Välj högst tre som passar uppgiften och läs bara dem. Ramverken styr resonemanget och nämns inte i den färdiga texten.',
    use: 'Använd när', avoid: 'Tänk på', principles: 'Principer', questions: 'Frågor att ställa', example: 'Påhittat exempel',
    before: 'Före', after: 'Efter', why: 'Varför', sources: 'Källor', checked: 'kontrollerad',
  },
  en: {
    index: 'Frameworks', intro: 'Choose at most three that fit the task and read only those. Frameworks guide the reasoning and are not named in the finished copy.',
    use: 'Use when', avoid: 'Keep in mind', principles: 'Principles', questions: 'Questions to ask', example: 'Fictional example',
    before: 'Before', after: 'After', why: 'Why', sources: 'Sources', checked: 'checked',
  },
};

function frameworkPage(f, language, notice) {
  const w = words[language];
  return [
    NOTE,
    `# ${f.title}`,
    `${f.author} · ${categoryLabels[f.category][language]} · \`${f.id}\``,
    f.summary,
    `**${w.use}:** ${f.useWhen}`,
    `**${w.avoid}:** ${f.avoidWhen}`,
    `## ${w.principles}\n\n${f.principles.map(p => `- ${p}`).join('\n')}`,
    `## ${w.questions}\n\n${f.questions.map(q => `- ${q}`).join('\n')}`,
    `## ${w.example}\n\n${f.example.context}\n\n- **${w.before}:** ${f.example.before}\n- **${w.after}:** ${f.example.after}\n- **${w.why}:** ${f.example.explanation}`,
    `## ${w.sources}\n\n${f.sources.map(s => `- [${s.title}](${s.url}) (${w.checked} ${s.checked})`).join('\n')}`,
    notice,
  ].join('\n\n') + '\n';
}

function frameworkIndex(library, language) {
  const w = words[language];
  const rows = library.list().map(({ id }) => library.get(id))
    .map(f => `- [${f.title}](frameworks/${language}/${f.id}.md) (${f.author}). ${f.useWhen}`);
  return [NOTE, `# ${w.index}`, w.intro, rows.join('\n'), library.notice.native].join('\n\n') + '\n';
}

// The checker is client/slop.js plus a command line, so the site, the MCP tool and the plugin find the same patterns.
const cli = `
// ---- Command line (generated by scripts/build-plugin.mjs; the patterns above are client/slop.js) ----
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

function main(argv) {
  let language = 'sv', json = false, file;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--lang') language = argv[++i];
    else if (arg === '--json') json = true;
    else if (!arg.startsWith('--') && file === undefined) file = arg;
    else { console.error('Usage: node check.mjs [--lang sv|en] [--json] [file]  (reads stdin without a file)'); return 2; }
  }
  if (language !== 'sv' && language !== 'en') { console.error('--lang must be sv or en'); return 2; }
  const index = language === 'en' ? 1 : 0;
  let text;
  try { text = readFileSync(file ?? 0, 'utf8'); } catch (error) { console.error((index ? 'Could not read the text: ' : 'Kunde inte läsa texten: ') + error.message); return 2; }
  const findings = findSlop(text).map(f => ({ pattern: f.label[index], quote: f.quote, fix: f.fix[index] }));
  if (json) { console.log(JSON.stringify({ language, count: findings.length, clean: findings.length === 0, findings }, null, 2)); return 0; }
  if (!findings.length) console.log(index ? 'No AI-writing patterns found.' : 'Inga AI-mönster hittades.');
  else {
    console.log(index ? findings.length + ' pattern(s) found. Make the minimum edit and keep the voice and facts.' : findings.length + ' mönster hittade. Gör minsta möjliga ändring och behåll rösten och fakta.');
    findings.forEach((f, n) => console.log((n + 1) + '. ' + f.pattern + ': "' + f.quote + '" -> ' + f.fix));
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main(process.argv.slice(2));
`;

/** Every generated file, as path → content. */
export async function pluginFiles(root = ROOT) {
  const files = new Map();
  const sv = await loadCopyLibrary(root, false);
  for (const language of ['sv', 'en']) {
    const library = sv.forLanguage(language);
    files.set(`${SKILLS}/write/references/frameworks-${language}.md`, frameworkIndex(library, language));
    for (const f of library.frameworks) files.set(`${SKILLS}/write/references/frameworks/${language}/${f.id}.md`, frameworkPage(f, language, library.notice.native));
  }
  const checker = '// Generated by scripts/build-plugin.mjs. Edit client/slop.js and run npm run build:plugin.\n' + await readFile(join(root, 'client/slop.js'), 'utf8') + cli;
  const read = file => readFile(join(root, SKILLS, 'write/references', file), 'utf8');
  const copies = { check: ['swedish.md', 'english.md'], review: ['swedish.md', 'english.md', 'chief.md'] };
  for (const skill of ['write', 'check', 'review']) {
    files.set(`${SKILLS}/${skill}/scripts/check.mjs`, checker);
    for (const file of copies[skill] ?? []) files.set(`${SKILLS}/${skill}/references/${file}`, await read(file));
  }
  return files;
}

/** Paths that differ from what the generator would write, plus generated files that should no longer exist. */
export async function stalePluginFiles(root = ROOT) {
  const files = await pluginFiles(root), stale = [];
  for (const [path, content] of files) {
    if (await readFile(join(root, path), 'utf8').catch(() => null) !== content) stale.push(path);
  }
  for (const language of ['sv', 'en']) {
    const dir = `${SKILLS}/write/references/frameworks/${language}`;
    for (const file of await readdir(join(root, dir)).catch(() => [])) if (!files.has(`${dir}/${file}`)) stale.push(`${dir}/${file}`);
  }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const stale = await stalePluginFiles();
    if (stale.length) { console.error('Out of date, run npm run build:plugin:\n' + stale.join('\n')); process.exitCode = 1; }
  } else {
    await rm(join(ROOT, SKILLS, 'write/references/frameworks'), { recursive: true, force: true });
    const files = await pluginFiles();
    for (const [path, content] of files) {
      await mkdir(dirname(join(ROOT, path)), { recursive: true });
      await writeFile(join(ROOT, path), content);
    }
    console.log(`Plugin: ${files.size} files written.`);
  }
}
